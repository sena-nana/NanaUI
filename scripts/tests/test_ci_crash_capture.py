import importlib.util
from pathlib import Path
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location(
    "ci_linux_crash_capture", ROOT / "scripts" / "ci-linux-crash-capture.py"
)
capture = importlib.util.module_from_spec(SPEC)
assert SPEC.loader is not None
SPEC.loader.exec_module(capture)


class CiLinuxCrashCaptureTests(unittest.TestCase):
    def test_find_core_files_matches_core_dumps_and_skips_text_and_dirs(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            core_dir = root / "cores"
            extra_dir = root / "cwd"
            core_dir.mkdir()
            extra_dir.mkdir()

            c1 = core_dir / "core.nana_gpu.1234.11"
            c1.write_bytes(b"ELF")
            c2 = extra_dir / "core"
            c2.write_bytes(b"ELF")
            (core_dir / "core.123.txt").write_text("not a core", encoding="utf-8")
            (core_dir / "core.subdir").mkdir()
            (core_dir / "unrelated.bin").write_bytes(b"0")

            found = capture.find_core_files(core_dir, extra_dirs=(extra_dir,))
            self.assertEqual([p.name for p in found], ["core.nana_gpu.1234.11", "core"])

    def test_parse_executable_from_file_and_gdb_outputs(self):
        file_out = (
            "ELF 64-bit LSB core file, x86-64, version 1 (SYSV), SVR4-style, "
            "from '/home/runner/work/NanaUI/target/debug/deps/nana_gpu-1234abcd', "
            "real uid: 1001, execfn: '/home/runner/work/NanaUI/target/debug/deps/nana_gpu-1234abcd'"
        )
        self.assertEqual(
            capture.parse_executable_from_file_output(file_out),
            "/home/runner/work/NanaUI/target/debug/deps/nana_gpu-1234abcd",
        )
        gdb_out = "exe = '/home/runner/work/NanaUI/target/debug/deps/contract-deadbeef'\n"
        self.assertEqual(
            capture.parse_executable_from_gdb_output(gdb_out),
            "/home/runner/work/NanaUI/target/debug/deps/contract-deadbeef",
        )

    def test_resolve_executable_falls_back_to_target_dir_comm_match(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            core = root / "core.nana_frame_exch.42.11"
            core.write_bytes(b"ELF")
            deps = root / "target" / "debug" / "deps"
            deps.mkdir(parents=True)
            bin_path = deps / "nana_frame_exchange-528ac5cb862e839f"
            bin_path.write_bytes(b"ELF")
            (deps / "nana_frame_exchange-528ac5cb862e839f.d").write_text("", encoding="utf-8")

            def fake_runner(cmd, *, timeout=15):
                return subprocess.CompletedProcess(cmd, 1, stdout="", stderr="")

            resolved = capture.resolve_executable(
                core, root / "target" / "debug", runner=fake_runner
            )
            self.assertEqual(resolved, bin_path)

    def test_summarize_gdb_backtrace_highlights_faulting_frames(self):
        sample = """
[New LWP 4201]
Core was generated by `/home/runner/target/debug/deps/nana_frame_exchange-1234`.
Program terminated with signal SIGSEGV, Segmentation fault.
#0  0x00007f1234567890 in llvmpipe_destroy () from /usr/lib/x86_64-linux-gnu/libvulkan_lvp.so

Thread 2 (LWP 4202):
#0  syscall () at ../sysdeps/unix/sysv/linux/x86_64/syscall.S:38

Thread 1 (LWP 4201):
#0  0x00007f1234567890 in llvmpipe_destroy () from /usr/lib/x86_64-linux-gnu/libvulkan_lvp.so
#1  0x00007f1234569999 in lvp_DestroyDevice () from /usr/lib/x86_64-linux-gnu/libvulkan_lvp.so
#2  0x0000555555667788 in wgpu_hal::vulkan::device::Device::drop ()
"""
        summary = capture.summarize_gdb_backtrace(sample, max_frames=2)
        self.assertIn("Program terminated with signal SIGSEGV", summary)
        self.assertIn("Thread 1 (LWP 4201):", summary)
        self.assertIn("llvmpipe_destroy", summary)
        self.assertIn("lvp_DestroyDevice", summary)
        self.assertNotIn("wgpu_hal::vulkan", summary)

    def test_collect_writes_env_and_summary_when_no_cores_found(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            core_dir = root / "cores"
            out_dir = root / "reports"
            core_dir.mkdir()
            pattern_file = root / "core_pattern"
            pattern_file.write_text("core.%e.%p\n", encoding="utf-8")

            def fake_runner(cmd, *, timeout=30):
                return subprocess.CompletedProcess(cmd, 0, stdout="ok", stderr="")

            rc = capture.collect(
                core_dir,
                out_dir,
                target_dir=root / "target" / "debug",
                runner=fake_runner,
                proc_core_pattern=pattern_file,
            )
            self.assertEqual(rc, 0)
            self.assertTrue((out_dir / "env.txt").is_file())
            self.assertIn("core_pattern: core.%e.%p", (out_dir / "env.txt").read_text())
            self.assertIn("No core files found", (out_dir / "summary.txt").read_text())


if __name__ == "__main__":
    unittest.main()
