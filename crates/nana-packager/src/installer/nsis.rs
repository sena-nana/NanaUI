//! NSIS `setup.exe`: an `.nsi` script generated from the application tree,
//! compiled by `makensis` on any host that has it (`NANA_MAKENSIS` names it
//! when it is not on `PATH`). The installer lists every file it installs,
//! and its uninstaller removes exactly those and the directories they
//! leave empty, never a whole directory tree: a user who installs into a
//! folder that holds other files keeps them.

use std::fmt::Write as _;
use std::path::Path;

use super::{InstallerInput, Meta, Outcome};
use crate::sign::tool::ToolCommand;
use crate::util::io;

const ARCHES: [(&str, &str); 4] = [
    ("x86_64", "x64"),
    ("aarch64", "arm64"),
    ("i686", "x86"),
    ("i586", "x86"),
];

/// `text` as literal content of an NSIS double-quoted string.
fn lit(text: &str) -> String {
    text.replace('$', "$$").replace('"', "$\\\"")
}

/// An NSIS double-quoted string of literal `text`.
fn quote(text: &str) -> String {
    format!("\"{}\"", lit(text))
}

/// `"<variable>\<literal>"`: an NSIS variable followed by literal text.
fn under(variable: &str, literal: &str) -> String {
    format!("\"{variable}\\{}\"", lit(literal))
}

pub(crate) fn script(
    input: &InstallerInput<'_>,
    meta: &Meta,
    out_file: &Path,
) -> Result<String, String> {
    let arch = super::arch(input.target, &ARCHES)?;
    let wide = arch != "x86";
    let version = super::wix::msi_version(&meta.version)?;
    let program_files = if wide {
        "$PROGRAMFILES64"
    } else {
        "$PROGRAMFILES"
    };
    let reg_view = if wide { "  SetRegView 64\n" } else { "" };
    let uninstall_key = format!(
        "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\{}",
        meta.id
    );
    let exe = input.layout.executable.replace('/', "\\");

    // Files grouped by directory, in a stable order.
    let mut files: Vec<(String, std::path::PathBuf)> = Vec::new();
    for path in crate::util::walk_files(input.app_root)? {
        let relative = crate::util::relative_path(input.app_root, &path)?;
        files.push((relative.replace('/', "\\"), path));
    }
    let mut install = String::new();
    let mut current_dir: Option<String> = None;
    let mut dirs: Vec<String> = Vec::new();
    for (relative, source) in &files {
        let dir = relative.rsplit_once('\\').map(|(dir, _)| dir.to_owned());
        if current_dir.as_ref() != Some(&dir.clone().unwrap_or_default()) {
            let target = match &dir {
                Some(dir) => under("$INSTDIR", dir),
                None => "\"$INSTDIR\"".into(),
            };
            writeln!(install, "  SetOutPath {target}").unwrap();
            current_dir = Some(dir.clone().unwrap_or_default());
        }
        if let Some(dir) = &dir {
            let mut prefix = String::new();
            for part in dir.split('\\') {
                if !prefix.is_empty() {
                    prefix.push('\\');
                }
                prefix.push_str(part);
                if !dirs.contains(&prefix) {
                    dirs.push(prefix.clone());
                }
            }
        }
        let source = std::path::absolute(source).map_err(io("resolve source"))?;
        writeln!(install, "  File {}", quote(&source.display().to_string())).unwrap();
    }
    let mut uninstall = String::new();
    for (relative, _) in &files {
        writeln!(uninstall, "  Delete {}", under("$INSTDIR", relative)).unwrap();
    }
    dirs.sort_by_key(|dir| std::cmp::Reverse(dir.matches('\\').count()));
    for dir in &dirs {
        writeln!(uninstall, "  RMDir {}", under("$INSTDIR", dir)).unwrap();
    }

    let key = quote(&uninstall_key);
    Ok(format!(
        "; Generated by nana-packager from the packaged application tree.
Unicode true
Name {name}
OutFile {out}
InstallDir {install_dir}
RequestExecutionLevel admin
SetCompressor /SOLID lzma
VIProductVersion \"{version}.0\"
VIAddVersionKey \"ProductName\" {name}
VIAddVersionKey \"ProductVersion\" {display_version}
VIAddVersionKey \"FileVersion\" {display_version}
VIAddVersionKey \"CompanyName\" {vendor}
VIAddVersionKey \"FileDescription\" {summary}

Page directory
Page instfiles
UninstPage uninstConfirm
UninstPage instfiles

Section \"Install\"
{reg_view}{install}  SetOutPath \"$INSTDIR\"
  WriteUninstaller \"$INSTDIR\\uninstall.exe\"
  CreateShortcut {shortcut} {target}
  WriteRegStr HKLM {key} \"DisplayName\" {name}
  WriteRegStr HKLM {key} \"DisplayVersion\" {display_version}
  WriteRegStr HKLM {key} \"Publisher\" {vendor}
  WriteRegStr HKLM {key} \"DisplayIcon\" {target}
  WriteRegStr HKLM {key} \"UninstallString\" '\"$INSTDIR\\uninstall.exe\"'
  WriteRegDWORD HKLM {key} \"NoModify\" 1
  WriteRegDWORD HKLM {key} \"NoRepair\" 1
SectionEnd

Section \"Uninstall\"
{reg_view}  Delete {shortcut}
{uninstall}  Delete \"$INSTDIR\\uninstall.exe\"
  RMDir \"$INSTDIR\"
  DeleteRegKey HKLM {key}
SectionEnd
",
        name = quote(&meta.name),
        out = quote(&out_file.display().to_string()),
        install_dir = under(program_files, &meta.name),
        display_version = quote(&meta.version),
        vendor = quote(&meta.vendor),
        summary = quote(&meta.summary),
        shortcut = under("$SMPROGRAMS", &format!("{}.lnk", meta.name)),
        target = under("$INSTDIR", &exe),
    ))
}

pub(super) fn build(
    input: &InstallerInput<'_>,
    meta: &Meta,
    dir: &Path,
    staging: &Path,
) -> Result<Outcome, String> {
    let arch = super::arch(input.target, &ARCHES)?;
    let path = dir.join(format!("{}-{}-{arch}-setup.exe", meta.stem, meta.version));
    let out_file = std::path::absolute(&path).map_err(io("resolve installer path"))?;
    let source = script(input, meta, &out_file)?;
    std::fs::create_dir_all(staging).map_err(io("create nsis staging"))?;
    let nsi = staging.join(format!("{}.nsi", meta.stem));
    std::fs::write(&nsi, source).map_err(io("write .nsi"))?;
    let Some(makensis) = super::find_tool(input, "makensis", Some("NANA_MAKENSIS")) else {
        return Ok(Outcome::NotExecuted {
            reason: "`makensis` is not on PATH (or set NANA_MAKENSIS); the .nsi is staged".into(),
            staged: Some(nsi),
        });
    };
    super::run(
        input.runner,
        &ToolCommand::new(makensis).args(["-V2", "-NOCD"]).arg(&nsi),
    )?;
    if !path.is_file() {
        return Err(format!(
            "makensis reported success but wrote no {}",
            path.display()
        ));
    }
    Ok(Outcome::Built {
        path,
        checks: Vec::new(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn nsis_strings_escape_variables_and_quotes() {
        assert_eq!(quote("a$b\"c"), "\"a$$b$\\\"c\"");
        assert_eq!(
            under("$INSTDIR", "run$time\\x"),
            "\"$INSTDIR\\run$$time\\x\""
        );
    }
}
